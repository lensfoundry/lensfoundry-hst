#!/usr/bin/env python
"""Fetch the data products from the Zenodo record into data/stamps/.

    uv run python scripts/fetch_data.py --sample slacs                 # one sample (its _all zip)
    uv run python scripts/fetch_data.py --sample slacs --filter f814W  # one filter only
    uv run python scripts/fetch_data.py --all                          # every sample
    uv run python scripts/fetch_data.py --check                        # verify what's present, download nothing

The repo tracks the hand-made products (masks, positions, info JSONs); the bulk data
(science stamps, noise maps, PSFs + error maps, dataset PNGs) ships in the Zenodo record
(concept DOI 10.5281/zenodo.24052764, pinned to a version in info/zenodo_archives.csv).
This script downloads the archive for the requested sample (or sample+filter) with pooch
(SHA256-verified against info/zenodo_archives.csv), extracts only files that are missing
or changed, and verifies every file against info/zenodo_files.csv afterwards. Re-running
is cheap: already-correct files are skipped, and the download itself is cached in the
pooch cache (~/.cache or the platform equivalent).

Both manifest CSVs are regenerated by make_zenodo_manifest.py when a new data version is
published.
"""
import argparse
import csv
import hashlib
import os
import sys
import zipfile

ws_path = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ARCHIVES_CSV = os.path.join(ws_path, 'info', 'zenodo_archives.csv')
FILES_CSV = os.path.join(ws_path, 'info', 'zenodo_files.csv')


def load_manifest():
    with open(ARCHIVES_CSV) as f:
        archives = {r['archive']: r for r in csv.DictReader(f)}
    files = {}
    with open(FILES_CSV) as f:
        for r in csv.DictReader(f):
            files.setdefault(r['archive'], []).append(r)
    return archives, files


def sha256_file(path):
    h = hashlib.sha256()
    with open(path, 'rb') as f:
        for chunk in iter(lambda: f.read(1 << 20), b''):
            h.update(chunk)
    return h.hexdigest()


def pick_archives(archives, sample, filt):
    """The archive(s) covering the request: <sample>_<filter>.zip for --filter (the
    smallest archive holding it), else <sample>_all.zip. bells (one filter) has only
    bells_all.zip, so a --filter request there resolves to the sample archive."""
    if filt:
        name = f'{sample}_{filt}.zip'
        if name not in archives:
            name = f'{sample}_all.zip'
            if name not in archives:
                raise SystemExit(f'no archive covers {sample}/{filt} '
                                 f'(known: {", ".join(sorted(archives))})')
        return [name]
    name = f'{sample}_all.zip'
    if name not in archives:
        raise SystemExit(f'no archive {name} in info/zenodo_archives.csv '
                         f'(regenerate with make_zenodo_manifest.py?)')
    return [name]


def fetch(archives, files, names, check_only=False):
    import pooch
    total_new = total_skip = 0
    for name in names:
        meta = archives[name]
        rows = files.get(name, [])
        # What is missing or changed in the working tree?
        want = []
        for r in rows:
            local = os.path.join(ws_path, r['path'])
            if not os.path.isfile(local) or sha256_file(local) != r['sha256']:
                want.append(r)
        if check_only:
            print(f'{name:24s} {len(rows) - len(want):5d} present & verified, '
                  f'{len(want):5d} missing/stale')
            total_new += len(want)
            continue
        if not want:
            print(f'{name:24s} all {len(rows)} files present and verified, nothing to do')
            total_skip += len(rows)
            continue
        print(f'{name:24s} downloading {int(meta["size_bytes"]) / 1e6:.0f} MB from Zenodo '
              f'({len(want)} of {len(rows)} files needed)...', flush=True)
        zpath = pooch.retrieve(meta['url'], known_hash=f"sha256:{meta['sha256']}",
                               fname=name, progressbar=True)
        wrote, failed = 0, []
        with zipfile.ZipFile(zpath) as z:
            contents = {m: z.read(m) for m in z.namelist() if m.startswith('data/')}
        for r in want:
            buf = contents.get(r['path'])
            if buf is None:
                failed.append((r['path'], 'not in archive'))
                continue
            if hashlib.sha256(buf).hexdigest() != r['sha256']:
                failed.append((r['path'], 'hash mismatch after download'))
                continue
            dest = os.path.join(ws_path, r['path'])
            os.makedirs(os.path.dirname(dest), exist_ok=True)
            with open(dest, 'wb') as f:
                f.write(buf)
            wrote += 1
        total_new += wrote
        total_skip += len(rows) - len(want)
        print(f'  extracted {wrote} files ({total_skip + wrote} verified present in total)')
        for path, why in failed:
            print(f'  FAILED: {path}: {why}', file=sys.stderr)
        if failed:
            return 1
    if check_only and total_new:
        print(f'\n{total_new} files missing or stale; fetch with e.g. '
              f'uv run python scripts/fetch_data.py --sample <sample>')
        return 1
    return 0


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    ap.add_argument('--sample', help='one sample (slacs, swells, gallery, bells, dinos, sl2s)')
    ap.add_argument('--filter', help='one filter of --sample, e.g. f814W (uses the smaller per-filter archive)')
    ap.add_argument('--all', action='store_true', help='every sample')
    ap.add_argument('--check', action='store_true', help='verify presence only, download nothing')
    a = ap.parse_args()
    if not a.all and not a.sample:
        ap.error('give --sample SAMPLE, or --all')
    if a.filter and not a.sample:
        ap.error('--filter needs --sample')

    archives, files = load_manifest()
    samples = sorted({n[:-len('_all.zip')] for n in archives if n.endswith('_all.zip')})
    names = []
    for s in (samples if a.all else [a.sample]):
        names += pick_archives(archives, s, a.filter if not a.all else None)
    sys.exit(fetch(archives, files, names, a.check))


if __name__ == '__main__':
    main()
